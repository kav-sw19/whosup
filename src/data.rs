/// A resume whosup just launched: the next process of that agent in that folder is that session.
#[derive(serde::Serialize, serde::Deserialize, Clone)]
struct PendingResume {
    key: String,
    tool: String,
    cwd: String,
    at: i64,
}

fn pending_file() -> PathBuf {
    crate::settings::dir().join("pending.json")
}

/// Note a resume so the process it starts is matched to the right session (it may not write
/// anything until you send a message, and pi hides its arguments).
pub fn expect_resume(key: &str, tool: Tool, cwd: &str) {
    let mut list: Vec<PendingResume> =
        fs::read_to_string(pending_file()).ok().and_then(|t| serde_json::from_str(&t).ok()).unwrap_or_default();
    let now = now_ms();
    list.retain(|p| now - p.at < 120_000 && p.key != key);
    list.push(PendingResume { key: key.to_string(), tool: tool.label().to_string(), cwd: cwd.to_string(), at: now });
    let _ = fs::create_dir_all(crate::settings::dir());
    if let Ok(json) = serde_json::to_string(&list) {
        let _ = fs::write(pending_file(), json);
    }
}

fn mtime_ms(p: &Path) -> i64 {
    fs::metadata(p)
        .and_then(|m| m.modified())
        .ok()
        .and_then(|t| t.duration_since(UNIX_EPOCH).ok())
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

/// Fill in `shared_files` for live sessions that edited the same file within the last hour.
pub fn mark_shared_files(sessions: &mut [Session], now: i64) {
    let hour = 60 * 60_000;
    let recent: Vec<(usize, Vec<String>)> = sessions
        .iter()
        .enumerate()
        .filter(|(_, s)| s.live())
        .map(|(i, s)| (i, s.t.files.iter().filter(|(_, at)| now - at < hour).map(|(f, _)| f.clone()).collect()))
        .collect();
    let mut shared: Vec<(usize, String, String, Option<String>)> = Vec::new();
    for (i, files) in &recent {
        for (j, other) in &recent {
            if i == j {
                continue;
            }
            for f in files.iter().filter(|f| other.contains(f)) {
                shared.push((*i, f.clone(), sessions[*j].title(), sessions[*j].tty.clone()));
            }
        }
    }
    for s in sessions.iter_mut() {
        s.shared_files.clear();
    }
    for (i, f, title, tty) in shared {
        sessions[i].shared_files.push((f, title, tty));
    }
}

static STUCK_AFTER_MS: std::sync::atomic::AtomicI64 = std::sync::atomic::AtomicI64::new(10 * 60_000);

/// How long one step may run before a session counts as stuck (`stuck_minutes=` in the config).
pub fn set_stuck_after_minutes(m: f64) {
    STUCK_AFTER_MS.store((m * 60_000.0) as i64, std::sync::atomic::Ordering::Relaxed);
}

fn stuck_after_ms() -> i64 {
    STUCK_AFTER_MS.load(std::sync::atomic::Ordering::Relaxed)
}

pub fn stuck_reason(t: &Transcript, live: bool, now: i64, after_ms: i64) -> Option<String> {
    if !live || !t.is_busy() {
        return None;
    }
    if t.call_repeats >= 3 && t.last_stop.as_deref() == Some("toolUse") || t.call_repeats >= 4 {
        let tool = t.last_call.as_deref().and_then(|c| c.split('|').next()).unwrap_or("tool");
        return Some(format!("looping? {tool} ×{}", t.call_repeats));
    }
    let quiet = now - t.last_ts?;
    if quiet >= after_ms {
        let what = match t.last_stop.as_deref() {
            Some("toolUse") => t.last_tool.clone().unwrap_or_else(|| "tool".into()),
            _ => "thinking".into(),
        };
        let m = quiet / 60_000;
        let dur = if m >= 60 { format!("{}h{}m", m / 60, m % 60) } else { format!("{m}m") };
        return Some(format!("stuck? {what} {dur}"));
    }
    None
}

/// Which of these files some process has open (one `lsof` call).
pub fn open_files(paths: &[PathBuf]) -> HashSet<PathBuf> {
    if paths.is_empty() {
        return HashSet::new();
    }
    let out = match std::process::Command::new("lsof").arg("-Fn").arg("--").args(paths).output() {
        Ok(o) => o,
        Err(_) => return HashSet::new(),
    };
    let wanted: HashSet<&PathBuf> = paths.iter().collect();
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .filter_map(|l| l.strip_prefix('n'))
        .map(PathBuf::from)
        .filter(|p| wanted.contains(p))
        .collect()
}

/// opencode sub-agents: child sessions (from its Task tool), with their own status and cost.
fn opencode_agents(s: &Session, parent_live: bool, children: &[crate::opencode::OcSession]) -> Vec<Agent> {
    let id = crate::opencode::id_of(&s.path).unwrap_or_default();
    children
        .iter()
        .filter(|c| c.parent.as_deref() == Some(id.as_str()))
        .map(|c| {
            let mut t = c.t.clone();
            crate::cost::fill(&mut t);
            let running = parent_live && t.is_busy();
            let status = match (running, t.last_stop.as_deref()) {
                (true, _) => "running",
                (false, Some("error")) => "error",
                (false, Some("aborted")) => "stopped",
                _ => "done",
            };
            Agent {
                key: format!("opencode-agent:{}", c.id),
                id: c.id.trim_start_matches("ses_").chars().take(7).collect(),
                agent: if c.agent.is_empty() { "agent".into() } else { c.agent.clone() },
                source: AgentSource::OpencodeTask,
                status: status.into(),
                running,
                task: t.name.clone().or(t.first_user.clone()).unwrap_or_default(),
                model: t.model.clone().unwrap_or_default(),
                effort: t.thinking.clone().unwrap_or_default(),
                activity: if running { t.activity() } else { status.into() },
                started: t.started,
                finished: if running { None } else { t.last_ts },
                last_activity: t.last_ts,
                turns: t.turns,
                tool_calls: t.tool_calls,
                tokens: t.tokens,
                cost: t.cost,
                last_text: t.last_text.clone(),
                path: Some(crate::opencode::path_for(&c.id)),
            }
        })
        .collect()
}

/// Codex sub-agents: `spawn_agent` calls in the thread, plus child threads that name it as
/// their parent (those carry their own transcript, so they show status, model and cost).
fn codex_agents(s: &Session, parent_live: bool, children: &[Session]) -> Vec<Agent> {
    let now = now_ms();
    let mut out: Vec<Agent> = Vec::new();
    for c in children.iter().filter(|c| c.t.parent_thread.as_deref() == Some(s.t.id.as_str())) {
        let running = parent_live && (c.t.is_busy() || now - c.mtime < 15 * 60_000) && c.t.last_stop.as_deref() != Some("stop");
        let status = if running { "running" } else if c.t.last_stop.as_deref() == Some("stop") { "done" } else { "stale" };
        out.push(Agent {
            key: format!("codex:{}", c.path.display()),
            id: c.t.id.chars().take(8).collect(),
            agent: c.t.name.clone().unwrap_or_else(|| "agent".into()),
            source: AgentSource::CodexAgent,
            status: status.into(),
            running,
            task: c.t.first_user.clone().unwrap_or_default(),
            model: c.t.model.clone().unwrap_or_default(),
            effort: c.t.thinking.clone().unwrap_or_default(),
            activity: if running { c.t.activity() } else { status.into() },
            started: c.t.started,
            finished: if running { None } else { c.t.last_ts },
            last_activity: c.t.last_ts,
            turns: c.t.turns,
            tool_calls: c.t.tool_calls,
            tokens: c.t.tokens,
            cost: c.t.cost,
            last_text: c.t.last_text.clone(),
            path: Some(c.path.clone()),
        });
    }
    for sp in &s.t.codex_spawns {
        // a child thread already describes this agent
        if out.iter().any(|a| a.agent == sp.name && !sp.name.is_empty()) {
            continue;
        }
        let done = sp.finished.is_some();
        let running = !done && parent_live;
        let status = if done { "done" } else if running { "running" } else { "stale" };
        out.push(Agent {
            key: format!("codex-spawn:{}:{}", s.key, sp.call_id),
            id: if sp.name.is_empty() { sp.call_id.chars().take(8).collect() } else { sp.name.clone() },
            agent: "agent".into(),
            source: AgentSource::CodexAgent,
            status: status.into(),
            running,
            task: sp.task.clone(),
            model: String::new(),
            effort: String::new(),
            activity: status.into(),
            started: sp.started,
            finished: sp.finished,
            last_activity: sp.finished.or(sp.started),
            turns: 0,
            tool_calls: 0,
            tokens: 0,
            cost: 0.0,
            last_text: sp.result.clone(),
            path: None,
        });
    }
    out
}

/// What whosup can see about a live Claude Code or Codex session's last tool request.
pub struct ApprovalSignals<'a> {
    pub last_role: Option<&'a str>,
    pub last_stop: Option<&'a str>,
    /// time since the transcript last changed
    pub quiet_ms: i64,
    /// a child process started since the request (the tool's command running)
    pub fresh_child: bool,
    pub cpu: f32,
    pub agents_running: bool,
    /// the agent recorded an approval request itself
    pub requested_by_agent: bool,
}

/// Is the agent waiting for you to approve a tool call? The transcript ends on the request
/// either way, so: nothing written for a few seconds, no command started for it, the agent
/// idle and no sub-agent busy means it's sitting at the approval prompt.
pub fn approval_pending(s: &ApprovalSignals) -> bool {
    if s.requested_by_agent {
        return true;
    }
    s.last_role == Some("assistant")
        && s.last_stop == Some("toolUse")
        && s.quiet_ms >= 4_000
        && !s.fresh_child
        && s.cpu < 3.0
        && !s.agents_running
}

/// `scout-5-a1-abb20485` -> `scout-5`
fn base_agent_id(id: &str) -> String {
    let parts: Vec<&str> = id.rsplitn(3, '-').collect();
    if parts.len() == 3
        && parts[0].chars().all(|c| c.is_ascii_hexdigit())
        && parts[1].starts_with('a')
        && parts[1][1..].chars().all(|c| c.is_ascii_digit())
    {
        parts[2].to_string()
    } else {
        id.to_string()
    }
}

