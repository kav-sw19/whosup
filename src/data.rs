impl Transcript {
    fn ingest(&mut self, tool: Tool, line: &str) {
        let Ok(v) = serde_json::from_str::<Value>(line) else { return };
        match tool {
            Tool::Pi => self.ingest_pi(&v),
            Tool::Claude => self.ingest_claude(&v),
            Tool::Codex => self.ingest_codex(&v),
            Tool::Opencode | Tool::Gemini | Tool::Aider | Tool::Other(_) => {}
        }
    }

    fn ingest_pi(&mut self, v: &Value) {
        let ts = ts_of(v);
        match v.get("type").and_then(Value::as_str).unwrap_or("") {
            "session" => {
                self.id = v.get("id").and_then(Value::as_str).unwrap_or("").into();
                self.cwd = v.get("cwd").and_then(Value::as_str).unwrap_or("").into();
                self.started = ts;
            }
            "session_info" => {
                if let Some(n) = v.get("name").and_then(Value::as_str) {
                    self.name = Some(n.into());
                }
            }
            "model_change" => {
                if let Some(m) = v.get("modelId").and_then(Value::as_str) {
                    self.model = Some(m.into());
                }
            }
            "thinking_level_change" => {
                if let Some(t) = v.get("thinkingLevel").and_then(Value::as_str) {
                    self.thinking = Some(t.into());
                }
            }
            "custom" if v.get("customType").and_then(Value::as_str) == Some("chalking-subagent") => {
                if let Some(d) = v.get("data") {
                    let s = |k: &str| d.get(k).and_then(Value::as_str).unwrap_or("").to_string();
                    let meta = AgentMeta {
                        id: s("id"),
                        agent: s("agent"),
                        task: s("task"),
                        status: s("status"),
                        model: s("model"),
                        effort: s("effort"),
                        turns: d.get("turns").and_then(Value::as_u64).unwrap_or(0),
                        tokens: d.get("tokens").and_then(Value::as_u64).unwrap_or(0),
                        cost: d.get("cost").and_then(Value::as_f64).unwrap_or(0.0),
                        started_at: d.get("startedAt").and_then(Value::as_i64),
                        finished_at: d.get("finishedAt").and_then(Value::as_i64),
                    };
                    // replace an earlier record of the same run
                    self.finished_agents
                        .retain(|m| !(m.id == meta.id && m.started_at == meta.started_at));
                    self.finished_agents.push(meta);
                }
            }
            "message" => {
                let Some(m) = v.get("message") else { return };
                let role = m.get("role").and_then(Value::as_str).unwrap_or("");
                if role == "system" {
                    return;
                }
                self.messages += 1;
                if ts.is_some() {
                    self.last_ts = ts;
                }
                self.last_role = Some(role.into());
                match role {
                    "user" => {
                        self.user_msgs += 1;
                        if let Some(t) = m.get("content").and_then(text_of) {
                            if self.first_user.is_none() {
                                self.first_user = Some(clip(&t, 4000));
                            }
                            self.last_user = Some(clip(&t, 4000));
                        }
                        self.last_stop = None;
                    }
                    "assistant" => {
                        self.turns += 1;
                        self.last_stop = m.get("stopReason").and_then(Value::as_str).map(Into::into);
                        if let Some(model) = m.get("model").and_then(Value::as_str) {
                            self.model = Some(model.into());
                        }
                        if let Some(u) = m.get("usage") {
                            let cost = u.pointer("/cost/total").and_then(Value::as_f64).unwrap_or(0.0);
                            self.cost += cost;
                            let tot = u.get("totalTokens").and_then(Value::as_u64).unwrap_or(0);
                            self.tokens += tot;
                            self.context_tokens = tot;
                            self.add_day(ts, cost, tot, false);
                        }
                        if let Some(parts) = m.get("content").and_then(Value::as_array) {
                            let calls: Vec<&Value> =
                                parts.iter().filter(|p| p.get("type").and_then(Value::as_str) == Some("toolCall")).collect();
                            let tools: Vec<String> =
                                calls.iter().filter_map(|p| p.get("name").and_then(Value::as_str).map(Into::into)).collect();
                            self.tool_calls += tools.len() as u64;
                            self.last_tool = if tools.is_empty() { None } else { Some(tools.join(", ")) };
                            for c in calls {
                                let name = c.get("name").and_then(Value::as_str).unwrap_or("tool");
                                self.note_call(name, c.get("arguments").unwrap_or(&Value::Null));
                            }
                        }
                        if let Some(t) = m.get("content").and_then(text_of) {
                            if !t.trim().is_empty() {
                                self.last_text = Some(clip(&t, 4000));
                            }
                        }
                    }
                    _ => {}
                }
            }
            _ => {}
        }
    }

    /// Add spend and tokens to the day of `ts`.
    pub(crate) fn add_day(&mut self, ts: Option<i64>, cost: f64, tokens: u64, estimated: bool) {
        let Some(ts) = ts.or(self.last_ts).or(self.started) else { return };
        let d = self.daily.entry(day_of(ts)).or_default();
        d.cost += cost;
        d.tokens += tokens;
        d.estimated |= estimated && cost > 0.0;
        if estimated {
            d.est_cost += cost;
        }
    }

    /// Record a tool call, counting identical calls in a row (a loop).
    pub(crate) fn note_call(&mut self, name: &str, args: &Value) {
        let sig = format!("{name}|{args}");
        if self.last_call.as_deref() == Some(sig.as_str()) {
            self.call_repeats += 1;
        } else {
            self.call_repeats = 1;
            self.last_call = Some(sig);
        }
        self.note_files(name, args);
    }

    /// Files a tool call writes: pi `edit`/`write`, Claude Code `Edit`/`Write`/`MultiEdit`/
    /// `NotebookEdit`, and `*** Update File:` lines in Codex's `apply_patch`.
    pub(crate) fn note_files(&mut self, name: &str, args: &Value) {
        let mut paths: Vec<String> = Vec::new();
        let lname = name.to_lowercase();
        if matches!(lname.as_str(), "edit" | "write" | "multiedit" | "notebookedit" | "multi_edit" | "write_file" | "edit_file") {
            for k in ["file_path", "path", "filePath", "notebook_path"] {
                if let Some(p) = args.get(k).and_then(Value::as_str) {
                    paths.push(p.to_string());
                    break;
                }
            }
        }
        // Codex's apply_patch: as its own tool (the patch is the input), or a shell command that
        // starts with `apply_patch` (patch text merely mentioned in some other call doesn't count)
        let command = args
            .get("cmd")
            .or(args.get("command"))
            .map(|c| match c {
                Value::Array(parts) => parts.iter().filter_map(Value::as_str).collect::<Vec<_>>().join(" "),
                other => other.as_str().unwrap_or("").to_string(),
            })
            .unwrap_or_default();
        let is_patch = lname == "apply_patch" || command.trim_start().starts_with("apply_patch");
        let text = match args {
            Value::String(s) => s.clone(),
            other => other.to_string(),
        };
        if is_patch {
            for line in text.split(['\n', '\\']).map(|l| l.trim_start_matches('n')) {
                for tag in ["*** Update File: ", "*** Add File: ", "*** Delete File: "] {
                    if let Some(p) = line.strip_prefix(tag) {
                        paths.push(p.trim().trim_end_matches('"').to_string());
                    }
                }
            }
        }
        let when = self.last_ts.unwrap_or(0);
        for p in paths {
            let abs = if p.starts_with('/') || self.cwd.is_empty() { p } else { format!("{}/{}", self.cwd.trim_end_matches('/'), p) };
            self.files.retain(|(f, _)| *f != abs);
            self.files.push((abs, when));
        }
        if self.files.len() > 300 {
            self.files.drain(..self.files.len() - 300);
        }
    }

    /// Short description of what the transcript is doing right now.
    pub fn activity(&self) -> String {
        match (self.last_role.as_deref(), self.last_stop.as_deref()) {
            (None, _) => "starting".into(),
            (Some("user"), _) | (Some("toolResult"), _) => "thinking…".into(),
            (Some("assistant"), Some("toolUse")) => {
                format!("⚙ {}", self.last_tool.clone().unwrap_or_else(|| "tool".into()))
            }
            (Some("assistant"), Some("stop")) | (Some("assistant"), Some("end_turn")) => "idle".into(),
            (Some("assistant"), Some(other)) => other.into(),
            (Some(r), _) => r.into(),
        }
    }

    pub fn is_busy(&self) -> bool {
        matches!(self.last_role.as_deref(), Some("user") | Some("toolResult"))
            || (self.last_role.as_deref() == Some("assistant") && self.last_stop.as_deref() == Some("toolUse"))
    }
}

struct CacheEntry {
    tool: Tool,
    offset: u64,
    partial: Vec<u8>,
    t: Transcript,
}

#[derive(Default)]
pub struct TranscriptCache {
    map: HashMap<PathBuf, CacheEntry>,
}

impl TranscriptCache {
    /// Parse only the bytes appended since the last call.
    pub fn get(&mut self, path: &Path, tool: Tool, sidechain: bool) -> Option<Transcript> {
        let len = fs::metadata(path).ok()?.len();
        let fresh = || CacheEntry {
            tool,
            offset: 0,
            partial: Vec::new(),
            t: Transcript { sidechain_file: sidechain, ..Transcript::default() },
        };
        let e = self.map.entry(path.to_path_buf()).or_insert_with(fresh);
        if len < e.offset || e.tool != tool {
            *e = fresh();
        }
        if len > e.offset {
            let mut f = fs::File::open(path).ok()?;
            f.seek(SeekFrom::Start(e.offset)).ok()?;
            let mut buf = Vec::with_capacity((len - e.offset) as usize);
            f.take(len - e.offset).read_to_end(&mut buf).ok()?;
            e.offset += buf.len() as u64;
            let mut data = std::mem::take(&mut e.partial);
            data.extend_from_slice(&buf);
            let mut start = 0;
            for i in 0..data.len() {
                if data[i] == b'\n' {
                    if let Ok(line) = std::str::from_utf8(&data[start..i]) {
                        if !line.trim().is_empty() {
                            e.t.ingest(e.tool, line);
                        }
                    }
                    start = i + 1;
                }
            }
            e.partial = data[start..].to_vec();
        }
        Some(e.t.clone())
    }

    pub fn retain(&mut self, keep: &HashSet<PathBuf>) {
        self.map.retain(|k, _| keep.contains(k));
    }
}

