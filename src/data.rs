//! Discovery of pi sessions, their processes and their sub-agents.
//!
//! Sources:
//! - `<agent_dir>/sessions/<cwd-slug>/<ts>_<id>.jsonl`        session transcripts
//! - `<agent_dir>/sessions/<cwd-slug>/<ts>_<id>.subagents/*.jsonl`  chalking sub-agent transcripts
//! - `custom` entries with customType `chalking-subagent` in the parent transcript (finished agents)
//! - `$TMPDIR/pi-subagents-*/async-subagent-runs/*/status.json`  pi-subagents background runs
//! - running `pi` processes (matched to sessions by cwd + start time)

use serde_json::Value;
use std::{
    collections::{HashMap, HashSet},
    fs,
    io::{Read, Seek, SeekFrom},
    path::{Path, PathBuf},
    time::{SystemTime, UNIX_EPOCH},
};
use crate::providers::Tool;
use sysinfo::{ProcessRefreshKind, ProcessesToUpdate, System, UpdateKind};

pub fn now_ms() -> i64 {
    SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_millis() as i64).unwrap_or(0)
}

/// days since 1970-01-01 for a civil date (Howard Hinnant's algorithm)
fn days_from_civil(y: i64, m: i64, d: i64) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = y - era * 400;
    let mp = (m + 9) % 12;
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146097 + doe - 719468
}

/// Parse `2026-10-15T12:00:18.852Z` or the filename form `2026-10-15T12-00-18-852Z` (UTC) to ms.
pub fn parse_ts(s: &str) -> Option<i64> {
    let nums: Vec<i64> = s
        .split(|c: char| !c.is_ascii_digit())
        .filter(|p| !p.is_empty())
        .take(7)
        .enumerate()
        .map(|(i, p)| if i == 6 { format!("{:0<3}", &p[..p.len().min(3)]).parse().ok() } else { p.parse().ok() })
        .collect::<Option<_>>()?;
    if nums.len() < 6 {
        return None;
    }
    let days = days_from_civil(nums[0], nums[1], nums[2]);
    let ms = nums.get(6).copied().unwrap_or(0);
    Some(((days * 24 + nums[3]) * 60 + nums[4]) * 60_000 + nums[5] * 1000 + ms)
}

fn ts_of(v: &Value) -> Option<i64> {
    match v.get("timestamp")? {
        Value::String(s) => parse_ts(s),
        Value::Number(n) => n.as_i64(),
        _ => None,
    }
}

fn text_of(content: &Value) -> Option<String> {
    match content {
        Value::String(s) => Some(s.clone()),
        Value::Array(parts) => {
            let t: Vec<&str> = parts
                .iter()
                .filter(|p| p.get("type").and_then(Value::as_str) == Some("text"))
                .filter_map(|p| p.get("text").and_then(Value::as_str))
                .collect();
            if t.is_empty() { None } else { Some(t.join("\n")) }
        }
        _ => None,
    }
}

fn clip(s: &str, n: usize) -> String {
    if s.chars().count() <= n { s.to_string() } else { s.chars().take(n).collect::<String>() + "…" }
}

#[derive(Clone, Debug, Default)]
pub struct AgentMeta {
    pub id: String,
    pub agent: String,
    pub task: String,
    pub status: String,
    pub model: String,
    pub effort: String,
    pub turns: u64,
    pub tokens: u64,
    pub cost: f64,
    pub started_at: Option<i64>,
    pub finished_at: Option<i64>,
}

/// Incrementally-parsed transcript summary.
#[derive(Clone, Debug, Default)]
pub struct Transcript {
    pub id: String,
    pub cwd: String,
    pub started: Option<i64>,
    pub name: Option<String>,
    pub model: Option<String>,
    pub thinking: Option<String>,
    pub messages: u64,
    pub user_msgs: u64,
    pub turns: u64,
    pub tool_calls: u64,
    pub cost: f64,
    pub tokens: u64,
    pub context_tokens: u64,
    pub last_ts: Option<i64>,
    pub last_role: Option<String>,
    pub last_stop: Option<String>,
    pub last_tool: Option<String>,
    pub first_user: Option<String>,
    pub last_user: Option<String>,
    pub last_text: Option<String>,
    pub finished_agents: Vec<AgentMeta>,
    /// title generated by the agent itself (Claude Code `ai-title`)
    pub auto_title: Option<String>,
    /// Codex `originator` (cli, desktop app, …)
    pub origin: Option<String>,
    pub(crate) last_msg_id: Option<String>,
    /// this file is itself a sub-agent transcript (keep sidechain lines)
    pub(crate) sidechain_file: bool,
}

impl Transcript {
    fn ingest(&mut self, tool: Tool, line: &str) {
        let Ok(v) = serde_json::from_str::<Value>(line) else { return };
        match tool {
            Tool::Pi => self.ingest_pi(&v),
            Tool::Claude => self.ingest_claude(&v),
            Tool::Codex => self.ingest_codex(&v),
            Tool::Other(_) => {}
        }
    }

    fn ingest_pi(&mut self, v: &Value) {
        let ts = ts_of(v);
        match v.get("type").and_then(Value::as_str).unwrap_or("") {
            "session" => {
                self.id = v.get("id").and_then(Value::as_str).unwrap_or("").into();
                self.cwd = v.get("cwd").and_then(Value::as_str).unwrap_or("").into();
                self.started = ts;
            }
            "session_info" => {
                if let Some(n) = v.get("name").and_then(Value::as_str) {
                    self.name = Some(n.into());
                }
            }
            "model_change" => {
                if let Some(m) = v.get("modelId").and_then(Value::as_str) {
                    self.model = Some(m.into());
                }
            }
            "thinking_level_change" => {
                if let Some(t) = v.get("thinkingLevel").and_then(Value::as_str) {
                    self.thinking = Some(t.into());
                }
            }
            "custom" if v.get("customType").and_then(Value::as_str) == Some("chalking-subagent") => {
                if let Some(d) = v.get("data") {
                    let s = |k: &str| d.get(k).and_then(Value::as_str).unwrap_or("").to_string();
                    let meta = AgentMeta {
                        id: s("id"),
                        agent: s("agent"),
                        task: s("task"),
                        status: s("status"),
                        model: s("model"),
                        effort: s("effort"),
                        turns: d.get("turns").and_then(Value::as_u64).unwrap_or(0),
                        tokens: d.get("tokens").and_then(Value::as_u64).unwrap_or(0),
                        cost: d.get("cost").and_then(Value::as_f64).unwrap_or(0.0),
                        started_at: d.get("startedAt").and_then(Value::as_i64),
                        finished_at: d.get("finishedAt").and_then(Value::as_i64),
                    };
                    // replace an earlier record of the same run
                    self.finished_agents
                        .retain(|m| !(m.id == meta.id && m.started_at == meta.started_at));
                    self.finished_agents.push(meta);
                }
            }
            "message" => {
                let Some(m) = v.get("message") else { return };
                let role = m.get("role").and_then(Value::as_str).unwrap_or("");
                if role == "system" {
                    return;
                }
                self.messages += 1;
                if ts.is_some() {
                    self.last_ts = ts;
                }
                self.last_role = Some(role.into());
                match role {
                    "user" => {
                        self.user_msgs += 1;
                        if let Some(t) = m.get("content").and_then(text_of) {
                            if self.first_user.is_none() {
                                self.first_user = Some(clip(&t, 4000));
                            }
                            self.last_user = Some(clip(&t, 4000));
                        }
                        self.last_stop = None;
                    }
                    "assistant" => {
                        self.turns += 1;
                        self.last_stop = m.get("stopReason").and_then(Value::as_str).map(Into::into);
                        if let Some(model) = m.get("model").and_then(Value::as_str) {
                            self.model = Some(model.into());
                        }
                        if let Some(u) = m.get("usage") {
                            self.cost += u.pointer("/cost/total").and_then(Value::as_f64).unwrap_or(0.0);
                            let tot = u.get("totalTokens").and_then(Value::as_u64).unwrap_or(0);
                            self.tokens += tot;
                            self.context_tokens = tot;
                        }
                        if let Some(parts) = m.get("content").and_then(Value::as_array) {
                            let tools: Vec<String> = parts
                                .iter()
                                .filter(|p| p.get("type").and_then(Value::as_str) == Some("toolCall"))
                                .filter_map(|p| p.get("name").and_then(Value::as_str).map(Into::into))
                                .collect();
                            self.tool_calls += tools.len() as u64;
                            self.last_tool = if tools.is_empty() { None } else { Some(tools.join(", ")) };
                        }
                        if let Some(t) = m.get("content").and_then(text_of) {
                            if !t.trim().is_empty() {
                                self.last_text = Some(clip(&t, 4000));
                            }
                        }
                    }
                    _ => {}
                }
            }
            _ => {}
        }
    }

    /// Short description of what the transcript is doing right now.
    pub fn activity(&self) -> String {
        match (self.last_role.as_deref(), self.last_stop.as_deref()) {
            (None, _) => "starting".into(),
            (Some("user"), _) | (Some("toolResult"), _) => "thinking…".into(),
            (Some("assistant"), Some("toolUse")) => {
                format!("⚙ {}", self.last_tool.clone().unwrap_or_else(|| "tool".into()))
            }
            (Some("assistant"), Some("stop")) | (Some("assistant"), Some("end_turn")) => "idle".into(),
            (Some("assistant"), Some(other)) => other.into(),
            (Some(r), _) => r.into(),
        }
    }

    pub fn is_busy(&self) -> bool {
        matches!(self.last_role.as_deref(), Some("user") | Some("toolResult"))
            || (self.last_role.as_deref() == Some("assistant") && self.last_stop.as_deref() == Some("toolUse"))
    }
}

struct CacheEntry {
    tool: Tool,
    offset: u64,
    partial: Vec<u8>,
    t: Transcript,
}

#[derive(Default)]
pub struct TranscriptCache {
    map: HashMap<PathBuf, CacheEntry>,
}

impl TranscriptCache {
    /// Parse only the bytes appended since the last call.
    pub fn get(&mut self, path: &Path, tool: Tool, sidechain: bool) -> Option<Transcript> {
        let len = fs::metadata(path).ok()?.len();
        let fresh = || CacheEntry {
            tool,
            offset: 0,
            partial: Vec::new(),
            t: Transcript { sidechain_file: sidechain, ..Transcript::default() },
        };
        let e = self.map.entry(path.to_path_buf()).or_insert_with(fresh);
        if len < e.offset || e.tool != tool {
            *e = fresh();
        }
        if len > e.offset {
            let mut f = fs::File::open(path).ok()?;
            f.seek(SeekFrom::Start(e.offset)).ok()?;
            let mut buf = Vec::with_capacity((len - e.offset) as usize);
            f.take(len - e.offset).read_to_end(&mut buf).ok()?;
            e.offset += buf.len() as u64;
            let mut data = std::mem::take(&mut e.partial);
            data.extend_from_slice(&buf);
            let mut start = 0;
            for i in 0..data.len() {
                if data[i] == b'\n' {
                    if let Ok(line) = std::str::from_utf8(&data[start..i]) {
                        if !line.trim().is_empty() {
                            e.t.ingest(e.tool, line);
                        }
                    }
                    start = i + 1;
                }
            }
            e.partial = data[start..].to_vec();
        }
        Some(e.t.clone())
    }

    pub fn retain(&mut self, keep: &HashSet<PathBuf>) {
        self.map.retain(|k, _| keep.contains(k));
    }
}

#[derive(Clone, Debug)]
