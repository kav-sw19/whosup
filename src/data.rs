#[derive(Clone, Debug)]
pub struct Session {
    /// files this session and another live one both edited in the last hour: (path, other
    /// session's title, its tty)
    pub shared_files: Vec<(String, String, Option<String>)>,
    /// waiting for you to approve a tool call (see `approval_pending`)
    pub awaiting_approval: bool,
    pub tool: Tool,
    /// The app it runs in (terminal emulator, editor, or the agent's own desktop app).
    pub host: Option<String>,
    /// live without a matched process (the Codex desktop app writes the transcript itself)
    pub app_live: bool,
    pub key: String,
    /// tty of the terminal this session runs in (`ttys001`)
    pub tty: Option<String>,
    pub path: PathBuf,
    pub t: Transcript,
    pub mtime: i64,
    pub proc: Option<ProcInfo>,
    pub agents: Vec<Agent>,
}

impl Session {
    pub fn live(&self) -> bool {
        self.proc.is_some() || self.app_live
    }
    pub fn title(&self) -> String {
        self.t.name.clone().or_else(|| self.t.auto_title.clone()).unwrap_or_else(|| {
            self.t
                .first_user
                .as_deref()
                .and_then(|s| {
                    s.lines()
                        .map(str::trim)
                        .find(|l| !l.is_empty() && !(l.starts_with('<') && l.ends_with('>')))
                        .map(|l| clip(l, 60))
                })
                .unwrap_or_else(|| "(new session)".into())
        })
    }
    /// A session not yet tied to a process or terminal.
    pub fn from_transcript(tool: Tool, path: PathBuf, t: Transcript, mtime: i64) -> Session {
        Session {
            shared_files: vec![],
            awaiting_approval: false,
            tool,
            host: None,
            app_live: false,
            key: format!("s:{}", path.display()),
            tty: None,
            path,
            t,
            mtime,
            proc: None,
            agents: vec![],
        }
    }

    /// Live and waiting on you: finished its turn, hit an error, wants a tool call approved, or
    /// looks stuck.
    pub fn needs_you(&self) -> bool {
        self.awaiting_approval
            || self.stuck().is_some()
            || self.live()
            && !self.t.is_busy()
            && self.t.last_role.as_deref() == Some("assistant")
            && matches!(self.t.last_stop.as_deref(), Some("stop") | Some("error"))
    }

    /// Why a live session looks stuck, if it does: one step running far too long, or the same
    /// tool call repeated.
    pub fn stuck(&self) -> Option<String> {
        stuck_reason(&self.t, self.live() && !self.awaiting_approval, now_ms(), stuck_after_ms())
    }

    /// Share of the context window in use (0.0–1.0+), when the window is known.
    pub fn context_used(&self) -> Option<f64> {
        let window = self.t.context_window.or_else(|| crate::models::window(self.t.model.as_deref()?))?;
        (window > 0 && self.t.context_tokens > 0).then(|| self.t.context_tokens as f64 / window as f64)
    }

    pub fn running_agents(&self) -> usize {
        self.agents.iter().filter(|a| a.running).count()
    }
}

