pub struct Scanner {
    pub agent_dir: PathBuf,
    pub claude_dir: PathBuf,
    pub codex_dir: PathBuf,
    pub recent_window_ms: i64,
    cache: TranscriptCache,
    sys: System,
    /// Codex thread titles from `session_index.jsonl` (id -> name), reloaded when it changes
    codex_titles: HashMap<String, String>,
    codex_index_mtime: i64,
}

fn mtime_ms(p: &Path) -> i64 {
    fs::metadata(p)
        .and_then(|m| m.modified())
        .ok()
        .and_then(|t| t.duration_since(UNIX_EPOCH).ok())
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

/// `scout-5-a1-abb20485` -> `scout-5`
fn base_agent_id(id: &str) -> String {
    let parts: Vec<&str> = id.rsplitn(3, '-').collect();
    if parts.len() == 3
        && parts[0].chars().all(|c| c.is_ascii_hexdigit())
        && parts[1].starts_with('a')
        && parts[1][1..].chars().all(|c| c.is_ascii_digit())
    {
        parts[2].to_string()
    } else {
        id.to_string()
    }
}

impl Scanner {
    pub fn new(agent_dir: PathBuf, recent_window_ms: i64) -> Self {
        let home = PathBuf::from(std::env::var("HOME").unwrap_or_default());
        let claude_dir = std::env::var_os("CLAUDE_CONFIG_DIR").map(PathBuf::from).unwrap_or_else(|| home.join(".claude"));
        let codex_dir = std::env::var_os("CODEX_HOME").map(PathBuf::from).unwrap_or_else(|| home.join(".codex"));
        Self {
            agent_dir,
            claude_dir,
            codex_dir,
            recent_window_ms,
            cache: TranscriptCache::default(),
            sys: System::new(),
            codex_titles: HashMap::new(),
            codex_index_mtime: 0,
        }
    }

    fn agent_processes(&mut self) -> Vec<ProcInfo> {
        self.sys.refresh_processes_specifics(
            ProcessesToUpdate::All,
            true,
            ProcessRefreshKind::nothing()
                .with_cmd(UpdateKind::OnlyIfNotSet)
                .with_cwd(UpdateKind::Always)
                .with_cpu()
                .with_memory(),
        );
        let me = std::process::id();
        let mut found: Vec<(sysinfo::Pid, Tool)> = Vec::new();
        for (pid, p) in self.sys.processes() {
            if pid.as_u32() == me {
                continue;
            }
            let argv0 = p.cmd().first().map(|s| s.to_string_lossy().to_string()).unwrap_or_default();
            let argv1 = p.cmd().get(1).map(|s| s.to_string_lossy().to_string());
            let name = p.name().to_string_lossy().to_string();
            if let Some(tool) = Tool::from_argv(&argv0, argv1.as_deref(), &name) {
                found.push((*pid, tool));
            }
        }
        // an agent's own helper processes (same tool as an ancestor) are not separate sessions
        let tool_of: HashMap<sysinfo::Pid, Tool> = found.iter().copied().collect();
        let mut out = Vec::new();
        for (pid, tool) in &found {
            let mut anc = self.sys.process(*pid).and_then(|p| p.parent());
            let mut nested = false;
            for _ in 0..8 {
                let Some(a) = anc else { break };
                if tool_of.get(&a) == Some(tool) {
                    nested = true;
                    break;
                }
                anc = self.sys.process(a).and_then(|p| p.parent());
            }
            if nested {
                continue;
            }
            let (pid, p) = (pid, self.sys.process(*pid).unwrap());
            out.push(ProcInfo {
                tool: *tool,
                pid: pid.as_u32(),
                start_ms: p.start_time() as i64 * 1000,
                cwd: p.cwd().map(|c| c.to_string_lossy().to_string()).unwrap_or_default(),
                cpu: p.cpu_usage(),
                mem: p.memory(),
            });
        }
        out.sort_by_key(|p| p.start_ms);
        out
    }

    fn async_runs(&self) -> Vec<(Option<String>, Agent)> {
        let mut out = Vec::new();
        let Ok(rd) = fs::read_dir(std::env::temp_dir()) else { return out };
        for root in rd.flatten() {
            if !root.file_name().to_string_lossy().starts_with("pi-subagents-") {
                continue;
            }
            let Ok(runs) = fs::read_dir(root.path().join("async-subagent-runs")) else { continue };
            for run in runs.flatten() {
                let sp = run.path().join("status.json");
                let Ok(txt) = fs::read_to_string(&sp) else { continue };
                let Ok(v) = serde_json::from_str::<Value>(&txt) else { continue };
                let s = |k: &str| v.get(k).and_then(Value::as_str).map(String::from);
                let state = s("state").unwrap_or_else(|| "unknown".into());
                let step0 = v.get("steps").and_then(Value::as_array).and_then(|a| a.first());
                let agent = s("agent")
                    .or_else(|| step0.and_then(|st| st.get("agent")).and_then(Value::as_str).map(String::from))
                    .unwrap_or_else(|| s("mode").unwrap_or_else(|| "subagent".into()));
                let task = s("task")
                    .or_else(|| step0.and_then(|st| st.get("task")).and_then(Value::as_str).map(String::from))
                    .unwrap_or_default();
                let run_id = s("runId").unwrap_or_else(|| run.file_name().to_string_lossy().into());
                let running = matches!(state.as_str(), "queued" | "running" | "paused");
                let activity = match (running, s("currentTool")) {
                    (true, Some(t)) => format!("⚙ {t}"),
                    (true, None) => s("activityState").unwrap_or_else(|| state.clone()),
                    _ => state.clone(),
                };
                out.push((
                    s("sessionId"),
                    Agent {
                        key: format!("async:{run_id}"),
                        id: run_id.chars().take(8).collect(),
                        agent,
                        source: AgentSource::PiSubagents,
                        status: state,
                        running,
                        task,
                        model: s("model").unwrap_or_default(),
                        effort: String::new(),
                        activity,
                        started: v.get("startedAt").and_then(Value::as_i64),
                        finished: v.get("endedAt").and_then(Value::as_i64),
                        last_activity: v.get("lastActivityAt").or(v.get("lastUpdate")).and_then(Value::as_i64),
                        turns: v.get("turnCount").and_then(Value::as_u64).unwrap_or(0),
                        tool_calls: v.get("toolCount").and_then(Value::as_u64).unwrap_or(0),
                        tokens: v.pointer("/totalTokens/total").and_then(Value::as_u64).unwrap_or(0),
                        cost: v.pointer("/totalCost/total").and_then(Value::as_f64).unwrap_or(0.0),
                        last_text: None,
                        path: Some(sp),
                    },
                ));
            }
        }
        out
    }

    fn chalking_agents(&mut self, session_path: &Path, parent: &Transcript, parent_live: bool) -> Vec<Agent> {
        let dir = session_path.with_extension("subagents");
        let mut agents = Vec::new();
        let mut used_meta: HashSet<usize> = HashSet::new();
        let now = now_ms();
        if let Ok(rd) = fs::read_dir(&dir) {
            for f in rd.flatten() {
                let p = f.path();
                if p.extension().and_then(|e| e.to_str()) != Some("jsonl") {
                    continue;
                }
                let Some(t) = self.cache.get(&p, Tool::Pi, true) else { continue };
                let mtime = mtime_ms(&p);
                let base = base_agent_id(&t.id);
                // finished record for this child: same id, closest start time
                let meta_idx = parent
                    .finished_agents
                    .iter()
                    .enumerate()
                    .filter(|(_, m)| m.id == base)
                    .filter(|(_, m)| match (m.started_at, t.started) {
                        (Some(a), Some(b)) => (a - b).abs() < 120_000,
                        _ => true,
                    })
                    .min_by_key(|(_, m)| (m.started_at.unwrap_or(0) - t.started.unwrap_or(0)).abs())
                    .map(|(i, _)| i);
                let meta = meta_idx.map(|i| {
                    used_meta.insert(i);
                    parent.finished_agents[i].clone()
                });
                let (status, running) = match &meta {
                    Some(m) => (m.status.clone(), false),
                    None if !parent_live => ("stale".into(), false),
                    None if t.is_busy() || now - mtime < 15 * 60_000 => ("running".into(), true),
                    None => ("stale".into(), false),
                };
                let agent_type = meta.as_ref().map(|m| m.agent.clone()).filter(|s| !s.is_empty()).unwrap_or_else(|| {
                    base.trim_end_matches(|c: char| c.is_ascii_digit()).trim_end_matches('-').to_string()
                });
                agents.push(Agent {
                    key: format!("chalk:{}", p.display()),
                    id: base,
                    agent: agent_type,
                    source: AgentSource::Chalking,
                    activity: if running { t.activity() } else { status.clone() },
                    status,
                    running,
                    task: meta.as_ref().map(|m| m.task.clone()).filter(|s| !s.is_empty()).or(t.first_user.clone()).unwrap_or_default(),
                    model: t.model.clone().or(meta.as_ref().map(|m| m.model.clone())).unwrap_or_default(),
                    effort: t.thinking.clone().or(meta.as_ref().map(|m| m.effort.clone())).unwrap_or_default(),
                    started: t.started,
                    finished: meta.as_ref().and_then(|m| m.finished_at),
                    last_activity: t.last_ts.or(Some(mtime)),
                    turns: t.turns,
                    tool_calls: t.tool_calls,
                    tokens: t.tokens,
                    cost: if t.cost > 0.0 { t.cost } else { meta.as_ref().map(|m| m.cost).unwrap_or(0.0) },
                    last_text: t.last_text.clone(),
                    path: Some(p),
                });
            }
        }
        // finished records whose transcript is gone
        for (i, m) in parent.finished_agents.iter().enumerate() {
            if used_meta.contains(&i) {
                continue;
            }
            agents.push(Agent {
                key: format!("meta:{}:{}:{}", session_path.display(), m.id, m.started_at.unwrap_or(0)),
                id: m.id.clone(),
                agent: m.agent.clone(),
                source: AgentSource::Chalking,
                status: m.status.clone(),
                running: false,
                task: m.task.clone(),
                model: m.model.clone(),
                effort: m.effort.clone(),
                activity: m.status.clone(),
                started: m.started_at,
                finished: m.finished_at,
                last_activity: m.finished_at,
                turns: m.turns,
                tool_calls: 0,
                tokens: m.tokens,
                cost: m.cost,
                last_text: None,
                path: None,
            });
        }
        agents
    }

    /// Every transcript file of every supported agent.
    fn transcript_files(&self) -> Vec<(PathBuf, Tool)> {
        fn jsonl_in(dir: &Path, out: &mut Vec<PathBuf>) {
            if let Ok(rd) = fs::read_dir(dir) {
                for f in rd.flatten() {
                    let p = f.path();
                    if p.extension().and_then(|e| e.to_str()) == Some("jsonl") {
                        out.push(p);
                    }
                }
            }
        }
        fn subdirs(dir: &Path) -> Vec<PathBuf> {
            fs::read_dir(dir)
                .map(|rd| rd.flatten().map(|e| e.path()).filter(|p| p.is_dir()).collect())
                .unwrap_or_default()
        }
        let mut out = Vec::new();
        let mut buf = Vec::new();
        for d in subdirs(&self.agent_dir.join("sessions")) {
            jsonl_in(&d, &mut buf);
        }
        out.extend(buf.drain(..).map(|p| (p, Tool::Pi)));
        for d in subdirs(&self.claude_dir.join("projects")) {
            jsonl_in(&d, &mut buf);
        }
        out.extend(buf.drain(..).map(|p| (p, Tool::Claude)));
        // ~/.codex/sessions/YYYY/MM/DD/rollout-*.jsonl
        for y in subdirs(&self.codex_dir.join("sessions")) {
            for m in subdirs(&y) {
                for d in subdirs(&m) {
                    jsonl_in(&d, &mut buf);
                }
            }
        }
        out.extend(buf.drain(..).map(|p| (p, Tool::Codex)));
        out
    }

    /// Claude Code Task-tool sub-agents: `<session>/subagents/agent-<id>.jsonl` (+ `.meta.json`).
    fn claude_agents(&mut self, session_path: &Path, parent_live: bool, keep: &mut HashSet<PathBuf>) -> Vec<Agent> {
        let dir = session_path.with_extension("").join("subagents");
        let Ok(rd) = fs::read_dir(&dir) else { return vec![] };
        let now = now_ms();
        let mut out = Vec::new();
        for f in rd.flatten() {
            let p = f.path();
            if p.extension().and_then(|e| e.to_str()) != Some("jsonl") {
                continue;
            }
            keep.insert(p.clone());
            let Some(t) = self.cache.get(&p, Tool::Claude, true) else { continue };
            let meta: Value = fs::read_to_string(p.with_extension("meta.json"))
                .ok()
                .and_then(|s| serde_json::from_str(&s).ok())
                .unwrap_or(Value::Null);
            let mtime = mtime_ms(&p);
            let finished = t.last_role.as_deref() == Some("assistant") && t.last_stop.as_deref() == Some("stop");
            let (status, running) = if finished {
                ("done".to_string(), false)
            } else if t.last_stop.as_deref() == Some("aborted") {
                ("stopped".to_string(), false)
            } else if parent_live && now - mtime < 30 * 60_000 {
                ("running".to_string(), true)
            } else {
                ("stale".to_string(), false)
            };
            let stem = p.file_stem().and_then(|s| s.to_str()).unwrap_or("agent");
            let id: String = stem.trim_start_matches("agent-").chars().take(7).collect();
            let desc = meta.get("description").and_then(Value::as_str).map(String::from);
            out.push(Agent {
                key: format!("claude:{}", p.display()),
                id,
                agent: meta.get("agentType").and_then(Value::as_str).unwrap_or("agent").to_string(),
                source: AgentSource::ClaudeTask,
                activity: if running { t.activity() } else { status.clone() },
                status,
                running,
                task: match (&desc, &t.first_user) {
                    (Some(d), Some(u)) => format!("{d}\n\n{u}"),
                    (Some(d), None) => d.clone(),
                    (None, Some(u)) => u.clone(),
                    (None, None) => String::new(),
                },
                model: t.model.clone().unwrap_or_default(),
                effort: String::new(),
                started: t.started,
                finished: if running { None } else { t.last_ts },
                last_activity: t.last_ts.or(Some(mtime)),
                turns: t.turns,
                tool_calls: t.tool_calls,
                tokens: t.tokens,
                cost: 0.0,
                last_text: t.last_text.clone(),
                path: Some(p),
            });
        }
        out
    }

    fn refresh_codex_titles(&mut self) {
        let path = self.codex_dir.join("session_index.jsonl");
        let mt = mtime_ms(&path);
        if mt == self.codex_index_mtime {
            return;
        }
        self.codex_index_mtime = mt;
        self.codex_titles.clear();
        for line in fs::read_to_string(&path).unwrap_or_default().lines() {
            if let Ok(v) = serde_json::from_str::<Value>(line) {
                if let (Some(id), Some(name)) = (v.get("id").and_then(Value::as_str), v.get("thread_name").and_then(Value::as_str)) {
                    self.codex_titles.insert(id.to_string(), name.to_string());
                }
            }
        }
    }

    pub fn scan(&mut self) -> Snapshot {
        let now = now_ms();
        let mut procs = self.agent_processes();
        let codex_app = self
            .sys
            .processes()
            .values()
            .any(|p| p.cmd().first().map(|a| a.to_string_lossy().contains("/Codex.app/Contents/MacOS/")).unwrap_or(false));

        // 1. candidate transcript files (recent, or touched since a live agent process started)
        let mut keep = HashSet::new();
        let mut sessions: Vec<Session> = Vec::new();
        for (p, tool) in self.transcript_files() {
            let mt = mtime_ms(&p);
            let near_proc = procs.iter().any(|pr| pr.tool == tool && mt >= pr.start_ms - 5_000);
            if now - mt > self.recent_window_ms && !near_proc {
                continue;
            }
            keep.insert(p.clone());
            let Some(mut t) = self.cache.get(&p, tool, false) else { continue };
            if t.started.is_none() && tool == Tool::Pi {
                t.started = p.file_name().and_then(|n| n.to_str()).and_then(|n| parse_ts(n.split('_').next()?));
            }
            if t.messages == 0 && t.cwd.is_empty() {
                continue; // nothing useful written yet
            }
            sessions.push(Session {
                tool,
                app_live: false,
                key: format!("s:{}", p.display()),
                tty: None,
                path: p,
                t,
                mtime: mt,
                proc: None,
                agents: vec![],
            });
        }

        // 2. match processes to sessions of the same agent: exact start-time match first,
        //    then the most recently written transcript in the same cwd
        let mut taken: HashSet<usize> = HashSet::new();
        let mut orphans = Vec::new();
        for pass in 0..2 {
            let mut rest = Vec::new();
            for pr in procs.drain(..) {
                let best = sessions
                    .iter()
                    .enumerate()
                    .filter(|(i, s)| !taken.contains(i) && s.tool == pr.tool && s.t.cwd == pr.cwd)
                    .filter(|(_, s)| match pass {
                        0 => s.t.started.map(|st| (st - pr.start_ms).abs() <= 15_000).unwrap_or(false),
                        _ => s.mtime >= pr.start_ms - 5_000,
                    })
                    .max_by_key(|(_, s)| s.mtime)
                    .map(|(i, _)| i);
                match best {
                    Some(i) => {
                        taken.insert(i);
                        sessions[i].proc = Some(pr);
                    }
                    None => rest.push(pr),
                }
            }
            procs = rest;
            if pass == 1 {
                orphans = std::mem::take(&mut procs);
            }
        }
        // sessions nobody has typed into, unless something is attached to them
        sessions.retain(|s| s.proc.is_some() || s.t.user_msgs > 0 || s.t.name.is_some());

        self.refresh_codex_titles();
        for s in sessions.iter_mut().filter(|s| s.tool == Tool::Codex && s.t.name.is_none()) {
            s.t.name = self.codex_titles.get(&s.t.id).cloned();
        }

        // Codex desktop threads have no process of their own: live while the app runs and the
        // thread was touched recently
        for s in sessions.iter_mut() {
            if s.tool == Tool::Codex && s.proc.is_none() && codex_app {
                let window = if s.t.is_busy() { 10 * 60_000 } else { 30 * 60_000 };
                s.app_live = now - s.mtime < window;
            }
        }

        // 3. agents
        let async_runs = self.async_runs();
        for s in sessions.iter_mut() {
            let live = s.live();
            let mut agents = match s.tool {
                Tool::Pi => self.chalking_agents(&s.path.clone(), &s.t, live),
                Tool::Claude => self.claude_agents(&s.path.clone(), live, &mut keep),
                _ => vec![],
            };
            for (sid, a) in &async_runs {
                if sid.as_deref() == Some(s.t.id.as_str()) {
                    agents.push(a.clone());
                }
            }
            if let Ok(rd) = fs::read_dir(s.path.with_extension("subagents")) {
                for f in rd.flatten() {
                    keep.insert(f.path());
                }
            }
            agents.sort_by_key(|a| (!a.running, std::cmp::Reverse(a.started.unwrap_or(0))));
            s.agents = agents;
        }
        // async runs that belong to no visible session
        let known: HashSet<String> = sessions.iter().map(|s| s.t.id.clone()).collect();
        let unattached: Vec<Agent> = async_runs
            .into_iter()
            .filter(|(sid, a)| a.running && !sid.as_ref().map(|x| known.contains(x)).unwrap_or(false))
            .map(|(_, a)| a)
            .collect();
        if !unattached.is_empty() {
            let mut t = Transcript::default();
            t.name = Some("(background runs, no session)".into());
            sessions.push(Session {
                tool: Tool::Pi,
                app_live: false,
                key: "s:unattached".into(),
                tty: None,
                path: PathBuf::new(),
                t,
                mtime: now,
                proc: None,
                agents: unattached,
            });
        }

        // 4. terminals, linked to the agent session running in their foreground
        let mut terminals = crate::terms::scan(&self.sys);
        for t in terminals.iter_mut() {
            for s in sessions.iter_mut() {
                let Some(pr) = &s.proc else { continue };
                if t.foreground.iter().any(|p| p.pid == pr.pid) {
                    t.session = Some(crate::terms::SessionLink { tool: s.tool, key: Some(s.key.clone()), title: s.title() });
                    s.tty = Some(t.tty.clone());
                }
            }
            for pr in &orphans {
                if t.session.is_none() && t.foreground.iter().any(|p| p.pid == pr.pid) {
                    t.session = Some(crate::terms::SessionLink {
                        tool: pr.tool,
                        key: Some(format!("p:{}", pr.pid)),
                        title: format!("{} session", pr.tool.label()),
                    });
                }
            }
        }

        self.cache.retain(&keep);
        sessions.sort_by_key(|s| (!s.live(), !(s.running_agents() > 0), std::cmp::Reverse(s.mtime)));
        Snapshot { sessions, orphan_procs: orphans, terminals }
    }
}

