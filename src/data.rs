//! Discovery of pi sessions, their processes and their sub-agents.
//!
//! Sources:
//! - `<agent_dir>/sessions/<cwd-slug>/<ts>_<id>.jsonl`        session transcripts
//! - `<agent_dir>/sessions/<cwd-slug>/<ts>_<id>.subagents/*.jsonl`  chalking sub-agent transcripts
//! - `custom` entries with customType `chalking-subagent` in the parent transcript (finished agents)
//! - `$TMPDIR/pi-subagents-*/async-subagent-runs/*/status.json`  pi-subagents background runs
//! - running `pi` processes (matched to sessions by cwd + start time)

